from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch()
    context = browser.new_context(locale="en-US", color_scheme="light", viewport={"width": 1440, "height": 960})
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto("http://localhost:5173", wait_until="domcontentloaded")
    expect(page.locator("#language")).to_have_value("en")
    expect(page.locator("html")).to_have_attribute("data-theme", "light")
    page.locator("#language").select_option("cs")
    expect(page.locator("html")).to_have_attribute("lang", "cs")
    expect(page.locator("h1")).to_have_text("Trocha života.Trocha klidu.")
    expect(page.locator("#feed span")).to_have_text("Nakrmit rybky")
    expect(page.locator(".hint")).to_contain_text("Tažením otáčejte")
    page.locator("#light").click()
    expect(page.locator("html")).to_have_attribute("data-theme", "dark")
    expect(page.locator("#light")).to_have_attribute("aria-label", "Zapnout světlý režim")
    page.locator("#customize").click()
    expect(page.locator("#editor-title")).to_have_text("Upravte si akvárium")
    assert page.locator("#reef-editor").evaluate("el => getComputedStyle(el).backgroundColor") == "rgba(24, 56, 61, 0.976)"
    expect(page.locator('label[for="count-castle"]')).to_have_text("Malé hrady")
    expect(page.locator('#terrain-type option[value="hills"]')).to_have_text("Mírné kopečky")
    expect(page.locator('#school-motion option[value="dart"]')).to_have_text("Hravé výpady")
    page.locator("#relief").fill("1.25")
    expect(page.locator("#relief-value")).to_have_text("1,25x")
    page.locator("#reset-reef").click()
    expect(page.locator("html")).to_have_attribute("lang", "cs")
    expect(page.locator("html")).to_have_attribute("data-theme", "dark")
    page.evaluate("""() => document.querySelectorAll('[id^="count-"]').forEach(el => {
      el.value = el.id === 'count-snail' ? 1 : 0;
      el.dispatchEvent(new Event('input', {bubbles:true}));
    })""")
    expect(page.locator(".edition")).to_have_text("1 malý život. Jeden drobný ekosystém.")
    page.locator("#reset-reef").click()
    expect(page.locator(".edition")).to_have_text("55 malých životů. Jeden drobný ekosystém.")
    page.locator("#close-editor").click()
    page.locator("#feed").click()
    expect(page.locator("#notice")).to_have_text("Malá svačinka. Už se sbíhají!")
    page.locator("#pause").click()
    expect(page.locator("#pause")).to_have_attribute("aria-label", "Spustit animaci")
    page.reload(wait_until="domcontentloaded")
    expect(page.locator("#language")).to_have_value("cs")
    expect(page.locator("html")).to_have_attribute("data-theme", "dark")
    page.screenshot(path="screenshots/aquarium-dark-cs.png")
    page.locator("#customize").click()
    page.set_viewport_size({"width": 390, "height": 844})
    assert page.locator("#reef-editor").evaluate("el => el.scrollWidth <= el.clientWidth")
    page.screenshot(path="screenshots/aquarium-dark-cs-mobile.png")
    page.locator("#close-editor").click()
    page.locator("#language").select_option("en")
    expect(page.locator("h1")).to_have_text("A little life.A little stillness.")
    expect(page.locator(".edition")).to_have_text("102 little lives. One tiny ecosystem.")
    page.locator("#customize").click()
    expect(page.locator("#editor-title")).to_have_text("Shape your reef")
    expect(page.locator('label[for="count-castle"]')).to_have_text("Miniature castles")
    page.locator("#close-editor").click()
    page.locator("#light").click()
    expect(page.locator("html")).to_have_attribute("data-theme", "light")
    page.reload(wait_until="domcontentloaded")
    expect(page.locator("#language")).to_have_value("en")
    expect(page.locator("html")).to_have_attribute("data-theme", "light")
    assert not errors, errors
    context.close()
    context = browser.new_context(locale="cs-CZ", color_scheme="dark")
    page = context.new_page()
    page.goto("http://localhost:5173", wait_until="domcontentloaded")
    expect(page.locator("#language")).to_have_value("cs")
    expect(page.locator("html")).to_have_attribute("data-theme", "dark")
    context.close()
    browser.close()
    print("PASS: full Czech UI, live translations, number formatting, dark/light palettes, persistence, reset, mobile layout, and system defaults; no runtime errors")
