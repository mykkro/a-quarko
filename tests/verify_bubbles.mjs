import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.js';
import {createBubbleBursts,bubbleDefaults} from '../dist/bubbles.js';

const scene=new THREE.Scene();scene.background=new THREE.Color('#c8e5df');scene.fog=new THREE.Fog('#c8e5df',23,56);
const settings={...bubbleDefaults},ground=()=>.8;
const bubbles=createBubbleBursts({scene,ground,getSettings:()=>settings,random:()=>.4});
assert.equal(scene.children.length,1);
assert.equal(scene.children[0].isPoints,true);
assert.equal(bubbles.snapshot().active,0);
bubbles.update(1);
assert.equal(bubbles.snapshot().lastKind,'fine');
assert(bubbles.snapshot().fine>100);
assert(bubbles.snapshot().first.position[1]>=ground()+.1);
const frozen=bubbles.snapshot();bubbles.update(0);assert.deepEqual(bubbles.snapshot(),frozen);
for(let i=0;i<20;i++)bubbles.update(.05);
assert(bubbles.snapshot().first.position[1]>frozen.first.position[1]);
assert(bubbles.snapshot().visible>100);
settings.bubbleMode='large';bubbles.clear(true);bubbles.burst();
assert(bubbles.snapshot().large>=9&&bubbles.snapshot().large<=18);
assert.equal(bubbles.snapshot().fine,0);
assert(bubbles.snapshot().first.radius>=.05);
settings.bubbleMode='fine';settings.bubbleStrength=2;bubbles.clear();
for(let i=0;i<10;i++)bubbles.burst();
assert(bubbles.snapshot().active<=bubbles.snapshot().capacity);
settings.bubbleMode='off';bubbles.update(.1);
assert.equal(bubbles.snapshot().active,0);assert.equal(bubbles.snapshot().visible,0);assert.equal(bubbles.burst(),false);
settings.bubbleMode='large';settings.bubbleInterval=35;bubbles.clear();bubbles.burst();
const total=bubbles.snapshot().totalBursts;
for(let i=0;i<160;i++)bubbles.update(.1);
assert.equal(bubbles.snapshot().active,0);assert.equal(bubbles.snapshot().totalBursts,total);
console.log('PASS: automatic bursts, fine/large sizes, ground origin, rise, pause, bounded pool, off mode and expiry');
